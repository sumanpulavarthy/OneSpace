import type { CodegenConfig } from '@graphql-codegen/cli';

/**
 * Generates TypeScript types for every operation in the app from the reviewed contract
 * (specs/graphql/schema.graphql). An operation that does not match the spec fails codegen, and a
 * type mismatch fails the build — this is the UI half of the schema drift check.
 * Operations are written in .ts files as template strings tagged with a GraphQL comment.
 */
const config: CodegenConfig = {
  schema: '../specs/graphql/schema.graphql',
  documents: ['src/app/**/*.operations.ts'],
  generates: {
    'src/app/graphql/generated.ts': {
      plugins: [
        { add: { content: '/* eslint-disable */\n// GENERATED by `npm run codegen` from specs/graphql/schema.graphql. Do not edit.' } },
        'typescript',
        'typescript-operations',
      ],
      config: {
        enumsAsTypes: true,
        avoidOptionals: { field: true, inputValue: false },
        scalars: { DateTime: 'string', Long: 'number' },
      },
    },
  },
  ignoreNoDocuments: false,
};

export default config;
